const q = (s: string) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

const locales = Object.keys(T);
let failed = 0;
for (const loc of locales) {
  const path = `src/lib/i18n/locales/${loc}/settings.ts`;
  let content = readFileSync(path, 'utf-8');
  const matches = [...content.matchAll(/noteColorProfileDesc:/g)];
  if (matches.length !== 2) {
    console.error(`✗ ${loc}: expected 2 noteColorProfileDesc occurrences, found ${matches.length}`);
    failed++;
    continue;
  }
  const settingsBlock = (indent: string) => Object.entries(T[loc].settings).map(([k, v]) => `${indent}${k}: ${q(v)},`).join('\n');
  const appearanceBlock = (indent: string) => Object.entries(T[loc].appearance).map(([k, v]) => `${indent}${k}: ${q(v)},`).join('\n');

  // Insert AFTER the second (appearance) occurrence first so indices stay valid.
  // Indentation is inherited from the anchor line (locales differ: 2 or 4 spaces).
  const idx2 = matches[1].index ?? -1;
  const line2Start = content.lastIndexOf('\n', idx2) + 1;
  const indent2 = content.slice(line2Start, idx2);
  const lineEnd2 = content.indexOf('\n', idx2);
  content = content.slice(0, lineEnd2 + 1) + appearanceBlock(indent2) + '\n' + content.slice(lineEnd2 + 1);

  const idx1 = matches[0].index ?? -1;
  const line1Start = content.lastIndexOf('\n', idx1) + 1;
  const indent1 = content.slice(line1Start, idx1);
  const lineEnd1 = content.indexOf('\n', idx1);
  content = content.slice(0, lineEnd1 + 1) + settingsBlock(indent1) + '\n' + content.slice(lineEnd1 + 1);

  writeFileSync(path, content);
  console.log(`✓ ${loc}: settings (+${Object.keys(T[loc].settings).length}) appearance (+${Object.keys(T[loc].appearance).length})`);
}
if (failed) process.exit(1);
console.log('done.');
