// Block builders
function kv(obj, indent) {
  return Object.entries(obj).map(([k, v]) => `${indent}${k}: ${q(v)},`).join('\n');
}

function achEntries(list, rtMap, isGame) {
  let out = '';
  for (const [sk, ck, name, dp, dg] of list) {
    const nm = Array.isArray(name) ? name[isGame ? 1 : 0] : name;
    const ds = isGame ? (dg ?? dp) : dp;
    const key = isGame ? ck : sk;
    out += `  ${key}: {\n    name: ${q(nm)},\n    description: ${q(ds)},\n`;
    if (isGame && rtMap && rtMap[ck] !== undefined) out += `    rewardTitle: ${q(rtMap[ck])},\n`;
    out += `  },\n`;
  }
  return out;
}

function apply(file, pairs) {
  let s = readFileSync(file, 'utf8');
  for (const [label, anchor, replacement] of pairs) {
    const n = s.split(anchor).length - 1;
    if (n === 1) continue;
    if (n === 0 && s.includes(replacement)) continue; // already applied in a previous run
    throw new Error(`${file} :: ${label}: anchor matched ${n} times`);
  }
  let applied = 0;
  for (const [label, anchor, replacement] of pairs) {
    if (!s.includes(anchor) && s.includes(replacement)) {
      console.log(`SKIP ${file} :: ${label} (already applied)`);
      continue;
    }
    s = s.replace(anchor, replacement);
    applied++;
  }
  writeFileSync(file, s);
  console.log(`OK ${file} (${applied} edits)`);
}

