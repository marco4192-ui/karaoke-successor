# The 14 non-EN/DE languages that need translations
NON_EN_DE = ['es','fr','it','pt','ja','ko','zh','ru','nl','pl','sv','no','da','fi']

for lang in NON_EN_DE:
    fp = os.path.join(BASE, lang, 'mobile.ts')
    with open(fp, 'r') as f:
        content = f.read()
    
    translations = TRANSLATIONS.get(lang, {})
    replaced = 0
    for key, value in translations.items():
        # Match pattern:    key: 'ENGLISH_VALUE',
        pattern = f"    {key}: '([^']*)'"
        replacement = f"    {key}: '{value}'"
        if re.search(pattern, content):
            content = re.sub(pattern, replacement, content)
            replaced += 1
    
    with open(fp, 'w') as f:
        f.write(content)
    
    print(f'  {lang}: {replaced} translations replaced')

print('\nAll translations applied!')
