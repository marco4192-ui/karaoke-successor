#!/usr/bin/env python3
"""1) Fix double comma in all 16 locale mobile.ts files.
2) Replace EN fallback translations with proper translations for all 14 non-EN/DE languages.
"""

import os, re

BASE = '/home/z/my-project/karaoke-successor/src/lib/i18n/locales'

# ============================================================
# PART 1: Fix double comma in all locale files
# ============================================================

LANGS = ['en','de','es','fr','it','pt','ja','ko','zh','ru','nl','pl','sv','no','da','fi']

for lang in LANGS:
    fp = os.path.join(BASE, lang, 'mobile.ts')
    with open(fp, 'r') as f:
        content = f.read()
    # Fix the double comma: find ",'',  } and replace with ",'\n  }
    # The pattern is: mirrorProfileSyncNote: '...'",,\n  },
    content = re.sub(r"(mirrorProfileSyncNote: '[^']*)',,\n  \}", r"\1',\n  }", content)
    with open(fp, 'w') as f:
        f.write(content)
    print(f'  Double-comma fix: {lang}')

print('\nDouble-comma fixes applied.')

